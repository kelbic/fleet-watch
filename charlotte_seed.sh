# Выполняется НА БОЕВОЙ через `ssh host bash -s`. Печатает: "<строк журнала за 24ч> <epoch последней пробы>"
# Две координаты (канон): ГЛУБИНА наблюдения (строк) и ВОЗРАСТ субъекта (метка пробы).
# Пусто во втором поле при ненулевом первом = журнал есть, проб нет => тишина >= 24ч.
# Ноль в первом = журнал не покрывает => возраст НЕИЗВЕСТЕН, врать нельзя.
J=$(journalctl -u liquidator-bot --since "-24h" --no-pager -o short-unix 2>/dev/null)
L=$(printf '%s' "$J" | grep -cE '^[0-9]')
P=$(printf '%s' "$J" | grep -E 'probe #|volley leg=' | tail -1 | cut -d' ' -f1 | cut -d. -f1)
echo "$L $P"
