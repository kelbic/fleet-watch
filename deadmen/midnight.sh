#!/bin/bash
# Dead-man для midnight-бота: алерт в TG, если executor.log молчит дольше, чем сам бот обещал.
#
# ПОЧЕМУ НЕ ФИКСИРОВАННЫЕ 600с, КАК У ОСТАЛЬНЫХ ТРЁХ (и почему деадмана тут не было вовсе):
# midnight — КАЛЕНДАРНЫЙ, а не гоночный. В мёртвое время он спит по POLL_IDLE=600с ШТАТНО,
# и порог 600с давал бы ложные срабатывания круглосуточно. Порог адаптивный, от самого бота.
#
# БАЗА ПОРОГА = ДЛИТЕЛЬНОСТЬ ПРОХОДА, А НЕ МЕЖПРОХОДНАЯ ПАУЗА (инцидент 22.07: спам).
# Бот пишет РОВНО ОДНУ строку на проход ("...целей=N за Nс след через Mс"). Пауза "след через M"
# крошечная (5с в HOT), НО сам проход на подтормаживающем узле идёт МОЛЧА сотни секунд (22.07:
# медиана ~700с, макс 829с). Если считать порог от паузы 5с (5×3+120=135с), КАЖДЫЙ штатный
# медленный проход читается как зависание — и deadman сыпал ~3 ложных 💀/час. Поэтому базу берём
# как max(пауза, худший из последних 8 проходов "за Nс"): в IDLE доминирует пауза 600с, в
# HOT-деградации — длительность прохода. Порог = база × 2 + 120с. Так штатно-медленный проход
# молчит, а настоящий стоп (лог не тикает > 2 проходов) ловится. Растущую длительность (не стоп,
# а деградацию) отдельно ловит 🐌-сигнал в самом боте — деадман только про ПОЛНОЕ молчание.
# 20.07 бот встал на 42 мин в IDLE, и НИКАКОЙ прибор этого не увидел: cron-watchdog проверяет,
# что процесс ЖИВ, а зависший процесс жив и держит flock. Деадман проверяет, что лог ТИКАЕТ.
LOG=/home/claude-agent/.midnight-bot/executor.log
STAMP=/home/claude-agent/.midnight-bot/.deadman_alerted
[ -f "$LOG" ] || exit 0

# ВОЗРАСТ ПО СТРОКЕ ГЛАВНОГО ЦИКЛА, А НЕ ПО mtime ФАЙЛА (урок katana, 01.08).
# В executor.log пишет не только рабочий цикл: у katana мемпул-слой держал файл «свежим»
# 11 часов после смерти сканера блоков, и mtime-деадман молчал всё это время (отставание
# 39,506 блоков, процесс жив и жёг ~98% ядра). Живость ЛОГА ≠ живость ЦИКЛА.
_last=$(grep -aoE '^\\[sched [0-9]{2}:[0-9]{2}:[0-9]{2}\\]' <(tail -n 5000 "$LOG") | tail -1 | tr -d '[]' | awk '{print $2}')
[ -n "$_last" ] || _last=$(grep -aoE '^\\[sched [0-9]{2}:[0-9]{2}:[0-9]{2}\\]' "$LOG" | tail -1 | tr -d '[]' | awk '{print $2}')
if [ -n "$_last" ]; then
  _now=$(date +%s); _t=$(date -d "$_last" +%s 2>/dev/null || echo "")
  [ -n "$_t" ] && [ "$_t" -gt "$_now" ] && _t=$(( _t - 86400 ))   # отметка без даты: вчера
  age=$(( _now - ${_t:-_now} ))
else
  age=$(( $(date +%s) - $(stat -c %Y "$LOG") ))   # строк цикла нет вовсе — тоже отказ
fi
# межпроходная пауза из последней строки с ней; если не нашли — консервативный дефолт 600
promised=$(grep -oE 'след через [0-9]+с' "$LOG" | tail -1 | grep -oE '[0-9]+')
[ -n "$promised" ] || promised=600
# худшая длительность прохода из последних 8 (одиночный быстрый проход НЕ должен занижать порог)
lastpass=$(grep -oE 'за [0-9]+с' "$LOG" | tail -8 | grep -oE '[0-9]+' | sort -n | tail -1)
[ -n "$lastpass" ] || lastpass=0
base=$promised; [ "$lastpass" -gt "$base" ] && base=$lastpass
limit=$(( base * 2 + 120 ))

if [ "$age" -gt "$limit" ]; then
  [ -f "$STAMP" ] && [ $(( $(date +%s) - $(stat -c %Y "$STAMP") )) -lt 3600 ] && exit 0
  mode=$(grep -oE '\] [A-Z]+/[A-Z]+' "$LOG" | tail -1 | awk '{print $2}')
  token=$(grep '^TELEGRAM_BOT_TOKEN=' /home/claude-agent/.claude/channels/telegram/.env 2>/dev/null | cut -d= -f2-)
  chat=$(grep -E '^(export )?MN_CHAT_ID=' /home/claude-agent/.midnight-bot/env 2>/dev/null | head -1 | cut -d= -f2- | awk '{print $1}')
  [ -n "$chat" ] || chat=265715923
  [ -n "$token" ] && curl -sm 10 "https://api.telegram.org/bot$token/sendMessage" \
    --data-urlencode "chat_id=$chat" \
    --data-urlencode "text=💀 [midnight] executor: лог молчит ${age}s (порог ${limit}s = проход ${base}s ×2 +120, режим ${mode:-?}) — завис. Cron-watchdog не поможет: процесс жив и держит flock." > /dev/null
  touch "$STAMP"
# else: НЕ трогаем STAMP. Раньше здесь был rm -f STAMP, и он стирал часовой дедуп на каждом
# тике в конце прохода — соседние медленные проходы алертили заново (спам 22.07). Теперь штамп
# держит паузу ровно 3600с и сам устаревает; на восстановлении просто протухнет без сброса.
fi
