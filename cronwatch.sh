# восстановления — скрипт отправил «✅ все задачи тикают» БУДУЧИ ПОЛНОСТЬЮ СЛЕПЫМ. Это ровно
# тот отказ, против которого весь скрипт. Поэтому: (1) арифметика только над проверенными
# числами, (2) «здорово» — не отсутствие тревоги, а доказанный факт.
#
# ЧЕГО ЭТОТ СКРИПТ НЕ УМЕЕТ (честная граница, не чините её видимостью покрытия):
#  * Журнал держит ~2 суток (persistent, кап 200 МБ; ЗАМЕР 19.09.2026 22:45 — глубина
#    174 300с = 48.42ч, и это ПИЛА: каждая ротация 16-МБ файла срезает ~2-3ч. Порог
#    суточной задачи — 172 920с = 48.03ч, то есть запас всего ~23 мин. Прежняя запись
#    «~2.3 суток» и «~3 суток» в комментарии wc-book относятся к более раннему замеру.
#    Если кап ужмут или логов станет больше, суточные задачи начнут уходить в
#    «НЕДОКАЗУЕМО» по построению — лечится свидетелем (4-е поле реестра), как у wc-book.)
