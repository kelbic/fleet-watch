  rm -f "$SSTAMP"
  t "слепой путь (нет journalctl), штамп снят"  1 probe
  rm -f "$SSTAMP"
  t "слепой путь, штамп снят повторно"          1 probe
  : > "$SSTAMP"
  t "слепой путь ПРИ взведённом штампе"         1 probe
  # 2) throttled не должна падать при недоступном stat
  t "throttled краш-безопасна без stat"         0 env PATH="$empty" CW_MUTE=1 /bin/bash -c \
      "STAMP=$SSTAMP; now=$now; THROTTLE=3600; $(declare -f throttled); throttled; true"
  # 3) ГАРД ПЕРВОЙ ВСТРЕЧИ (регрессия ложного 💀 20.08 17:00).
  # Фикстура — НАСТОЯЩИЙ журнал без строк одной задачи: мир, где она не запускалась ни разу.
  prod_seen=$(cat "$DIR/cronwatch.seen" 2>/dev/null)
  fix=$sand/snap
  # ЗОНД ФИКСТУРЫ ОБЯЗАН БЫТЬ В РЕЕСТРЕ. До 18.09 здесь стоял cu-quota — его сняли из
  # реестра ревью флота 10.09 и НЕ тронули стенд. С этого дня ветка «старая задача не
  # запускалась = смерть» проверялась на задаче, которой в реестре нет: тревоги нет по
  # построению, тест падал, и единственная проверка, ловящая «cron перестал звать
  # сторожа», стояла мёртвой 8 суток. Ровно [[retired-subject-needs-watchdog-sweep]]:
  # вывод субъекта не глушит сторожа, а убивает его специфичность.
  journalctl -u cron --since "-13h" --no-pager -o short-unix 2>/dev/null \
    | grep 'CMD (' 2>/dev/null | grep -v 'fleet-watch/agent-wake.py' > "$fix" 2>/dev/null
  fixlines=$(grep -c 'CMD (' "$fix" 2>/dev/null); case "$fixlines" in (''|*[!0-9]*) fixlines=0 ;; esac
  if [ "$fixlines" -lt "$MIN_CMD_LINES" ]; then
    echo "  ПРОПУСК гарда первой встречи: журнал дал $fixlines строк (<$MIN_CMD_LINES) — фикстуру не построить"
  else
    gprobe() { env CW_MUTE=1 CW_DIR="$sand" CW_LOG="$SLOG" CW_STATE="$SSTATE" \
                   CW_STAMP="$SSTAMP" CW_SEEN="$1" CW_SNAP_FILE="$fix" /bin/bash "$(/usr/bin/readlink -f "$0")"; }
    # (а) задача ТОЛЬКО ЧТО в реестре -> пустота в журнале НЕ является смертью -> код 0
    printf 'agent-wake|%s\n' "$now" > "$sand/seen_new"
    rm -f "$SSTAMP"
    t "новая задача без запусков — НЕ тревога"   0 gprobe "$sand/seen_new"
    # (б) та же пустота у задачи, известной сутки -> это смерть -> код 2
    printf 'agent-wake|%s\n' "$(( now - 86400 ))" > "$sand/seen_old"
    rm -f "$SSTAMP"
    t "старая задача без запусков — ТРЕВОГА"     2 gprobe "$sand/seen_old"
    # (в,г) СВИДЕТЕЛЬ (19.09). У месячной задачи журнал КОРОЧЕ порога всегда, значит обе
    # ветки её вердикта решает mtime файла-свидетеля — и обе обязаны быть проверены, иначе
    # «зарегистрирован в cronwatch» означало бы надзор, которого нет. Свидетель лежит в
    # $DIR, а в стенде $DIR — песочница, поэтому боевой файл сторожа не трогается.
    printf 'wc-book|%s\n' "$(( now - 99999999 ))" > "$sand/seen_wit"
    : > "$sand/wc-book-watch.state"
    rm -f "$SSTAMP"
    t "месячная задача: свежий свидетель — НЕ тревога"  0 gprobe "$sand/seen_wit"
    rm -f "$sand/wc-book-watch.state"
    rm -f "$SSTAMP"
    t "месячная задача: свидетеля нет — ТРЕВОГА"        2 gprobe "$sand/seen_wit"
  fi

  # 3b) ГАРД ОБЩЕГО ПРОСТОЯ ИСТОЧНИКА (регрессия ложного 💀 19.09 12:30:56).
  # Фикстуры СИНТЕЗИРУЮТСЯ ИЗ НАСТОЯЩЕГО журнала (вырезанием отрезка/строк задачи и
  # сдвигом времён к now), а не пишутся под ответ. Обе ветки обязательны: без негативного
  # контроля гард просто глушил бы надзор, и «зелено» означало бы слепоту.
  if [ "$fixlines" -ge "$MIN_CMD_LINES" ]; then
    _shift() {  # $1=вход $2=выход $3=вырезать с (сек до конца) $4=вырезать по $5=что ещё
                # выбросить в ХВОСТЕ (d<=$4): так воспроизводится 19.09 — источник догнал
                # залпом, а обвинённая задача свой следующий запуск ещё не получила.
      awk -v c1="$3" -v c2="$4" -v pat="$5" '{t=$1+0; if (t>mx) mx=t; a[NR]=$0; ts[NR]=t}
        END{ for(i=1;i<=NR;i++){ d=mx-ts[i];
             if (d<=c1 && d>c2) continue;
             if (pat!="" && d<=c2 && index(a[i],pat)>0) continue;
             print a[i] } }' "$1" > "$2".raw 2>/dev/null
      # СДВИГ АНКЕРИТСЯ НА ИСХОДНЫЙ МАКСИМУМ, А НЕ НА МАКСИМУМ ОБРЕЗКА. Якорь по обрезку
      # схлопывает сам провал: если в хвосте (d<=$4) стояли ТОЛЬКО строки выброшенной задачи,
      # новейшей в обрезке становится её же строка из-за провала (d≈420с) — и сдвиг пришпиливал
      # ЕЁ к now-2, делая фикстуру «всё свежо». Ровно так стенд и покраснел в 12:44Z.
      local mx; mx=$(cut -d. -f1 "$1" | sort -n | tail -1)
      case "$mx" in (''|*[!0-9]*) mx=0 ;; esac
      awk -v d="$(( now - 2 - mx ))" '{t=$1+0; sub(/^[0-9.]+/, sprintf("%d.000000", t+d)); print}' "$2".raw > "$2"
      rm -f "$2".raw
    }
    # (д) ПОЗИТИВНЫЙ КОНТРОЛЬ: весь cron молчал ~6 мин и догнал 40с назад -> НЕ тревога.
    _shift "$fix" "$sand/snap_stall" 400 40 'midnight-executor.lock'
    _em=$(grep -F 'midnight-executor.lock' "$sand/snap_stall" | tail -1 | cut -d. -f1)
    case "$_em" in (''|*[!0-9]*) _em=$now ;; esac
    _emage=$(( now - _em ))
    # ОБЕ предпосылки проверяются явно. Гард применим, только когда задача молчит дольше
    # порога И источник жив сейчас; без второй проверки зелень «не тревога» могла бы прийти
    # по причине, к гарду не относящейся.
    _gn=$(tail -1 "$sand/snap_stall" | cut -d. -f1)
    case "$_gn" in (''|*[!0-9]*) _gn=0 ;; esac
    _gnage=$(( now - _gn ))
    if [ "$_emage" -le 240 ] || [ "$_gnage" -gt "$SRC_FRESH" ]; then
      echo "  ПРОВАЛ СТЕНДА: фикстура затора не воспроизводит условие (exec-midnight ${_emage}с ≤ 240с либо источник несвеж ${_gnage}с > ${SRC_FRESH}с)"
      fails=$(( fails + 1 ))
    else
      rm -f "$SSTAMP"
      t "общий простой источника (${_emage}с, источник свеж ${_gnage}с) — НЕ тревога"  0 gprobe "$sand/seen_new"
    fi
    # (е) НЕГАТИВНЫЙ КОНТРОЛЬ: источник тикает, замолчала ОДНА задача -> тревога остаётся.
    grep -v 'fleet-netwatch.lock' "$fix" > "$sand/fix_nonw" 2>/dev/null
    grep 'fleet-netwatch.lock' "$fix" 2>/dev/null | head -20 >> "$sand/fix_nonw"
    sort -n "$sand/fix_nonw" -o "$sand/fix_nonw"
    _shift "$sand/fix_nonw" "$sand/snap_dead" -1 -1 ''
    rm -f "$SSTAMP"
    t "источник жив, одна задача молчит — ТРЕВОГА"  2 env CW_MUTE=1 CW_DIR="$sand" \
        CW_LOG="$SLOG" CW_STATE="$SSTATE" CW_STAMP="$SSTAMP" CW_SEEN="$sand/seen_new" \
        CW_SNAP_FILE="$sand/snap_dead" /bin/bash "$(/usr/bin/readlink -f "$0")"
  fi

  # 4) боевые артефакты обязаны остаться нетронутыми
  t "боевой state не тронут тестом"             0 test "$(cat "$DIR/cronwatch.state" 2>/dev/null)" = "$prod_state"
  t "боевой реестр встреч не тронут тестом"     0 test "$(cat "$DIR/cronwatch.seen" 2>/dev/null)" = "$prod_seen"
  rm -rf "$sand"; rmdir "$empty" 2>/dev/null
  echo "провалов: $fails"
  VERIFIED=1; ALARMED=1
  [ "$fails" -eq 0 ] || exit 1
  exit 0
fi

# внутренний режим для selftest: тот же путь, но гарантированно без сети
[ "${1:-}" = "_blindprobe" ] && WINDOW="-12h"

# ── ИСТОЧНИК ИСТИНЫ ─────────────────────────────────────────────────────────────
# CW_SNAP_FILE — ТОЛЬКО для регрессии решающей логики (selftest). Подменяется ИСТОЧНИК
# ДАННЫХ, а не решение: дальше идёт тот же самый код, что и в бою. Фикстура строится из
# НАСТОЯЩЕГО журнала вычёркиванием строк одной задачи (мир «задача не запускалась»), а не
# пишется под ожидаемый ответ — списанная с продукта фикстура зелена ровно там, где бой слеп.
if [ -n "${CW_SNAP_FILE:-}" ] && [ -f "${CW_SNAP_FILE:-}" ]; then
  SNAP=$(cat "$CW_SNAP_FILE")
  lines=$(printf '%s\n' "$SNAP" | grep -c 'CMD (' 2>/dev/null)
  case "$lines" in (''|*[!0-9]*) lines=0 ;; esac
else
  # ГОНКА С РОТАЦИЕЙ ЖУРНАЛА (замерено 19.09.2026, ложная тревога 22:30:02).
  # journald пишет system.journal кусками по 16 МБ и при переполнении переименовывает
  # активный файл в архивный, создавая новый. В 22:30:02.104 такая ротация совпала с
  # выборкой cronwatch ПО СЕКУНДЕ (mtime архива system@...-00065bdaf565ca0a.journal), и
  # journalctl вернул 6 строк вместо 10 992 — при ЖИВОМ кроне и целом журнале
  # (journalctl --verify: PASS по всем файлам; 12 повторов того же запроса в 22:40 дали
  # 10 994 строки без разброса). Ротация идёт ~10 раз в сутки, выборка — 96 раз, поэтому
  # пересечение редкое, но неизбежное: одиночный пустой ответ НЕ является доказательством
  # слепоты. Механизм ВНУТРИ journalctl (почему выпали и архивные файлы) не наблюдался —
  # его stderr уходил в /dev/null; теперь он сохраняется и печатается в лог.
  # FAIL-SAFE НЕ ОСЛАБЛЕН: ретрай не может превратить слепоту в «здорово». Он лишь
  # требует, чтобы слепота ПОВТОРИЛАСЬ; если пусты все попытки — ниже идёт ровно прежний
  # путь СЛЕП с тревогой и exit 1. Настоящая поломка журнала/прав живёт дольше 6 секунд.
  BLIND_TRIES=${CW_BLIND_TRIES:-3}
  case "$BLIND_TRIES" in (''|*[!0-9]*) BLIND_TRIES=3 ;; esac
  [ "$BLIND_TRIES" -lt 1 ] && BLIND_TRIES=1
  _try=1
  while : ; do
    _jerr=$(mktemp 2>/dev/null) || _jerr=""
    if [ -n "$_jerr" ]; then
      SNAP=$(journalctl -u cron --since "$WINDOW" --no-pager -o short-unix 2>"$_jerr" | grep 'CMD (' 2>/dev/null)
    else
      SNAP=$(journalctl -u cron --since "$WINDOW" --no-pager -o short-unix 2>/dev/null | grep 'CMD (' 2>/dev/null)
    fi
    lines=$(printf '%s\n' "$SNAP" | grep -c 'CMD (' 2>/dev/null)
    case "$lines" in (''|*[!0-9]*) lines=0 ;; esac
    [ "$lines" -ge "$MIN_CMD_LINES" ] && { [ -n "$_jerr" ] && rm -f "$_jerr"; break; }
    # Пустое чтение — НАЗВАТЬ ПРИЧИНУ, а не только факт: stderr journalctl и есть то, чего
    # не хватило при разборе 19.09 (гипотезу о механизме пришлось оставить недоказанной).
    _emsg=""
    [ -n "$_jerr" ] && [ -f "$_jerr" ] && _emsg=$(tr '\n' ' ' < "$_jerr" 2>/dev/null)
    [ -n "$_jerr" ] && rm -f "$_jerr"
    log "СЛЕПОЕ ЧТЕНИЕ #$_try/$BLIND_TRIES: $lines строк CMD за $WINDOW (порог $MIN_CMD_LINES) stderr=[${_emsg:0:200}]"
    [ "$_try" -ge "$BLIND_TRIES" ] && break
    _try=$(( _try + 1 ))
    /bin/sleep 3 2>/dev/null || true   # абсолютный путь: selftest гоняет с пустым PATH
  done
fi

# ПАДАТЬ ГРОМКО: нет журнала — нет проверки. Это тревога, а не тишина.
if [ "$lines" -lt "$MIN_CMD_LINES" ]; then
  log "СЛЕП: journalctl дал $lines строк CMD за $WINDOW (порог $MIN_CMD_LINES)"
  printf '{"ts":%s,"verified":false,"reason":"blind","lines":%s}\n' "$now" "$lines" > "$STATE" 2>/dev/null
  alarm "🔴 [cronwatch] СЛЕП: journalctl дал $lines строк CMD за $WINDOW. Надзор за сторожами НЕ РАБОТАЕТ — проверить journald/права."
  exit 1
fi

# ── ПРОВЕРКА РЕЕСТРА ────────────────────────────────────────────────────────────
# Насколько ГЛУБОК журнал на самом деле: расширить окно запросом мало — journald мог хранить
# меньше. Если журнал короче порога задачи, её смерть НЕДОКАЗУЕМА, и объявлять её мёртвой
# нельзя: это ровно та ложная тревога, из-за которой на сторожа перестают смотреть.
oldest=$(printf '%s\n' "$SNAP" | head -1 | cut -d. -f1)
case "$oldest" in (''|*[!0-9]*) oldest=$now ;; esac
span=$(( now - oldest ))

# ПЕРВАЯ ВСТРЕЧА ЗАДАЧИ (20.08). «В журнале нет запусков» доказывает смерть только у задачи,
# которая ОБЯЗАНА была запускаться всё это время. У ТОЛЬКО ЧТО ЗАВЕДЁННОЙ пустота в журнале —
# нормальное состояние, и 20.08 17:00 это дало ложное 💀: cu-quota добавили в crontab и в
# реестр в 16:59, первый запуск стоял на :07, а глубина журнала (13ч) уже перекрывала порог
# задачи (7320с) — гард «span<limit» такую задачу не спасает по построению.
# Поэтому вторая координата: КОГДА задача впервые появилась в реестре. Файл дописывается
# только новыми именами; отсутствие/непрочитанность файла = задача считается новой (fail-safe
# в сторону молчания у ОДНОЙ задачи, а не ложной тревоги по всему флоту).
# ПЕРВИЧНОЕ ЗАПОЛНЕНИЕ. Если файла ещё нет, все задачи, УЖЕ стоящие в реестре, засеваются
# возрастом «$now - $span» (насколько хватает журнала), а НЕ текущим моментом. Иначе введение
# самого гарда ослепило бы надзор на один порог по КАЖДОЙ задаче разом — у route-canary это
# 12 часов молчания о реально умершем стороже. Гард обязан защищать только имена, появившиеся
# ПОСЛЕ него; для всех сегодняшних задач семантика остаётся ровно прежней.
if [ ! -f "$SEEN" ]; then
  : > "$SEEN" 2>/dev/null || true
  _seed=$(( now - span ))
  for e in "${REGISTRY[@]}"; do
    printf '%s|%s\n' "${e%%|*}" "$_seed" >> "$SEEN" 2>/dev/null || true
  done
  log "реестр первых встреч создан: ${#REGISTRY[@]} задач засеяны возрастом ${span}с (глубина журнала)"
fi
touch "$SEEN" 2>/dev/null || true

# ── ОБЩИЙ ПРОСТОЙ ИСТОЧНИКА (19.09, ложное 💀 12:30:56) ────────────────────────
# Живость задачи мерится ЧУЖИМ журналом, и журнал этот ОБЩИЙ. 19.09 12:25..12:29 хост
# ушёл в своп (swap 1952/2047 МБ, load 17.5) и cron не вызвал НИ ОДНОЙ задачи — ноль строк
# CMD у всех, затем залп 17 штук в 12:30. Молчали все, а обвинён был exec-midnight: у него
# самый тугой порог (каденция 60с -> 240с), остальные пятиминутный провал пережили. Бот при
# этом не прерывался ни на минуту (строка [sched] в executor.log есть в каждой минуте окна).
# Это отказ ОБЩЕЙ МОДЫ: свойство источника приписывается субъекту. Поэтому из молчания
# задачи вычитается тот отрезок, когда молчал ВЕСЬ источник, и порог судит остаток.
#
# ПОЧЕМУ ЭТО НЕ ГЛУШИТ НАСТОЯЩУЮ СМЕРТЬ КРОНА: вычитание разрешено, только если источник
# ЖИВ СЕЙЧАС (новейшая CMD-строка свежее SRC_FRESH). Если cron лежит в этот момент, простой
# тянется до now, gnew велик, вычитание запрещено — и тревога уходит как прежде. Незнание
# закрывает гард, а не открывает.
gnewts=$(printf '%s\n' "$SNAP" | tail -1 | cut -d. -f1)
case "$gnewts" in (''|*[!0-9]*) gnewts=0 ;; esac
gnew=$(( now - gnewts ))

host_gap() {  # $1=отметка последнего запуска задачи. Печатает МАКСИМАЛЬНЫЙ разрыв между
              # соседними CMD-строками ЛЮБЫХ задач на отрезке [$1, now].
  printf '%s\n' "$SNAP" | cut -d. -f1 | grep -E '^[0-9]+$' 2>/dev/null \
    | awk -v from="$1" -v now="$now" '
        $1 >= from { if (prev != "") { d = $1 - prev; if (d > max) max = d } ; prev = $1 }
        END { if (prev != "") { d = now - prev; if (d > max) max = d } ; print max+0 }'
}

bad=""; report=""; unproven=""; stalled=""
for e in "${REGISTRY[@]}"; do
  name=${e%%|*}; rest=${e#*|}; pat=${rest%%|*}; cad=${rest#*|}; wit=""
  case "$cad" in (*'|'*) wit=${cad#*|}; cad=${cad%%|*} ;; esac
  [ -n "$wit" ] && wit="$DIR/$wit"
  last=$(printf '%s\n' "$SNAP" | grep -F "$pat" 2>/dev/null | tail -1 | cut -d. -f1)
  case "$last" in (''|*[!0-9]*) last="" ;; esac
  limit=$(( cad * 2 + GRACE ))
  # ЯКОРЬ ^: grep -F совпадает где угодно в строке, и имя-суффикс чужого имени читало бы
  # ЧУЖУЮ первую встречу. Сегодня в реестре коллизий нет — но молчаливо неверный возраст
  # у одного сторожа не даёт симптома, а именно им гард и решает, звонить ли.
  first=$(grep "^$name|" "$SEEN" 2>/dev/null | tail -1 | cut -d'|' -f2)
  case "$first" in (''|*[!0-9]*) first="" ;; esac
  if [ -z "$first" ]; then
    printf '%s|%s\n' "$name" "$now" >> "$SEEN" 2>/dev/null || true
    first=$now
  fi
  known=$(( now - first ))
  if [ -z "$last" ]; then
    age=-1
    if [ -n "$wit" ]; then
      # СВИДЕТЕЛЬ: файл, который задача переписывает КАЖДЫМ успешным прогоном. mtime —
      # внешнее по отношению к задаче доказательство запуска (сам скрипт о себе не
      # отчитывается), ровно как journalctl для остальных. Нет файла = wage -1.
      wage=-1
      if [ -f "$wit" ]; then
        wmt=$(stat -c %Y "$wit" 2>/dev/null)
        case "$wmt" in (''|*[!0-9]*) wmt="" ;; esac
        [ -n "$wmt" ] && wage=$(( now - wmt ))
      fi
      if [ "$wage" -ge 0 ] && [ "$wage" -le "$limit" ]; then
        age=$wage
      elif [ "$known" -lt "$limit" ]; then
        unproven="$unproven $name(НОВАЯ, в реестре ${known}с<${limit}с)"
      else
        bad="$bad\n  🔴 $name — свидетель $wit ${wage}с > порога ${limit}с (каденция ${cad}с), запусков в журнале нет"
      fi
    elif [ "$span" -lt "$limit" ]; then
      unproven="$unproven $name(журнал ${span}с<${limit}с)"
    elif [ "$known" -lt "$limit" ]; then
      unproven="$unproven $name(НОВАЯ, в реестре ${known}с<${limit}с)"
    else
      bad="$bad\n  🔴 $name — НИ ОДНОГО запуска за ${span}с журнала (каденция ${cad}с, в реестре ${known}с)"
    fi
  else
    age=$(( now - last ))
    if [ "$age" -gt "$limit" ]; then
      hgap=$(host_gap "$last")
      case "$hgap" in (''|*[!0-9]*) hgap=0 ;; esac
      own=$(( age - hgap ))
      if [ "$gnew" -le "$SRC_FRESH" ] && [ "$own" -le "$limit" ]; then
        stalled="$stalled $name(${age}с − простой источника ${hgap}с = ${own}с ≤ ${limit}с)"
      else
        bad="$bad\n  ⚠️ $name — молчит ${age}с > порога ${limit}с (каденция ${cad}с)"
      fi
    fi
  fi
  report="$report$name=${age}s/${cad}s "
done

log "проверено ${#REGISTRY[@]} задач | окно ${WINDOW#-} глубина журнала ${span}с | $report"
[ -n "$unproven" ] && log "НЕДОКАЗУЕМО (журнал короче порога задачи):$unproven"
if [ -n "$stalled" ]; then
  # Не «сторож не тикает», а «хост встал»: субъект другой, адресат тот же (агент).
  # Само событие молчанием не покрывается — пятиминутный затор перед боевым окном
  # стоит знать, но будить им человека нечем: разгребает агент.
  log "ЗАТОР ИСТОЧНИКА (молчание объяснено общим простоем cron, задача не обвиняется):$stalled"
  tg "$(printf '⚠️ [cronwatch] ЗАТОР ХОСТА: cron не вызывал НИ ОДНОЙ задачи какое-то время, затем догнал.\nЗадеты порогом (обвинение снято):%s\n\nСторожа живы — молчал общий источник. Смотреть нагрузку/своп на машине.' "$stalled")" "cronwatch:stall"
fi

if [ -n "$bad" ]; then
  printf '{"ts":%s,"verified":true,"checked":%s,"bad":true}\n' "$now" "${#REGISTRY[@]}" > "$STATE" 2>/dev/null
  VERIFIED=1
  alarm "$(printf '💀 [cronwatch] СТОРОЖА НЕ ТИКАЮТ:%b\n\nПорог = каденция×2+120с. Источник — journalctl cron (внешний, задачи в нём не участвуют).' "$bad")"
  exit 2
fi

# всё проверено и всё в норме — единственная точка, где это можно утверждать
printf '{"ts":%s,"verified":true,"checked":%s,"bad":false}\n' "$now" "${#REGISTRY[@]}" > "$STATE" 2>/dev/null
VERIFIED=1
if [ -f "$STAMP" ]; then
  rm -f "$STAMP"
  tg "✅ [cronwatch] все ${#REGISTRY[@]} задач снова тикают в срок." "cronwatch:ok"
fi
exit 0
