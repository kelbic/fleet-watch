#!/bin/bash
# ЛОКАЛЬНЫЙ помощник сторожа: одной строкой отвечает на вопрос, ради которого 💀 и поднимается —
# «был ли исход, который мы обязаны были взять». Знаменатель тревоги о бездействии лежит НЕ в
# журнале бота (28.08: шесть признаков проверены, ни один не разделяет), а в цепи.
# Печатает: "<число призовых блоков> <последний ts> <последний блок> <погашено>"  либо "0 - - -"
L=/home/claude-agent/.fleet-watch/prize-watch.log
S=/home/claude-agent/.fleet-watch/prize_watch.state
[ -r "$L" ] || { echo "0 - - -"; exit 0; }
awk '
  /^[0-9]{4}-[0-9]{2}-[0-9]{2}T/ { ts=$1 }
  /блок [0-9]+: ликвидаций/ {
     b=$2; sub(/:$/,"",b);
     if (!(b in seen)) { seen[b]=1; n++ }
     last_ts=ts; last_b=b;
     if (match($0, /погашено ~\$[0-9.]+/)) last_p=substr($0, RSTART+10, RLENGTH-10);
  }
  END { printf "%d %s %s %s\n", n+0, (last_ts==""?"-":last_ts), (last_b==""?"-":last_b), (last_p==""?"-":last_p) }
' "$L"
