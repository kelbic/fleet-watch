#!/bin/bash
# СТОРОЖ ТРЕДОВ боевого бота (21.08, заказ kelbic после двух штормов «can't start new thread»).
# TasksMax поднят 256->1024 КЛАПАНОМ, не фиксом: треды растут как темп_проб x латентность
# квитанций, жирный каскад может дойти до нового предела. Порог 600 (~60%) — шторм ловится
# ДО отказа спавна, а не по трейсбекам. Адресат — ИНБОКС АГЕНТА (hil=0): структурный фикс
# (коллектор на путь окна) делает агент, человеку тут решать нечего.
#
# НОЛЬ — ЭТО НЕ ЗДОРОВЬЕ (21.08, найдено при разборе первой же тревоги). `systemctl show -p
# MainPID` у остановленной или несуществующей службы отдаёт 0; `ls /proc/0/task | wc -l` = 0;
# ноль — ЧИСЛО, поэтому старый гард слепоты его пропускал, писал в лог «threads=0», обнулял
# счётчик слепых прогонов и молчал. Мёртвый бот читался как здоровый И ГЛУШИЛ собственную
# тревогу о слепоте — ровно класс «мёртвый сторож хуже отсутствующего». Незнание обязано
# закрывать гард: N<1 = не наблюдаем, а не «спокойно», и в лог такой прогон НЕ пишется
# (иначе он травит распределение, по которому позже калибруется порог).
#
# КОНТРОЛЬ ТРУБЫ — только с ключом на ':selftest' (notify.py кладёт такое сразу в архив
# разобранного). Живой вызов с обычным ключом 21.08 15:01 поднял сессию разбора на тест.
set -u
# Пути и адресат переопределяемы из окружения — ЧТОБЫ ТЕСТ НЕ ТРОГАЛ БОЕВЫЕ АРТЕФАКТЫ
# (тот же приём, что в cronwatch.sh: счётчик слепых прогонов и лог-распределение, испорченные
# прогоном теста, — это та же ложная уверенность, против которой сторож и стоит).
F=${TW_FAILS:-~/.fleet-watch/threads-watch.fails}
LOG=${TW_LOG:-~/.fleet-watch/threads-watch.log}
NOTIFY=${TW_NOTIFY:-~/.fleet-watch/notify.sh}
HOST=${TW_HOST:-root@185.173.146.134}
RETIRED=${TW_RETIRED:-$HOME/.fleet-watch/RETIRED-liquidator-bot.md}

# ВЫВОД ИЗ ЭКСПЛУАТАЦИИ — НЕ АВАРИЯ (31.08, крон-триаж тревоги threads-botdown). Бот
# остановлен и disabled НАМЕРЕННО, весь капитал выведен свипом (боевой кошелёк 0.0000013 ETH
# ЗАМЕРЕН cast-ом, не со слов) — «MainPID=0» теперь ИСТИННОЕ и ПОСТОЯННОЕ состояние, и
# сторож звонил бы им каждые 6ч вечно. Ложная тревога дороже молчания: на неё перестают
# смотреть, а вместе с ней перестают смотреть и на настоящую (память alerts-only-where-human-acts).
# ГАСИМ НЕ ПОРОГ И НЕ ТЕКСТ, А СУБЪЕКТ: пока лежит маркер — наблюдать нечего, и сторож это
# ГОВОРИТ ВСЛУХ, а не молчит (мёртвый сторож хуже отсутствующего: молчаливый ранний exit
# неотличим от «cron меня не зовёт»). Внешний надзор cronwatch этим не ломается — он берёт
# истину из journalctl о ВЫЗОВЕ, а не из этого лога.
# ВОЗВРАТ — УДАЛЕНИЕ ФАЙЛА: маркер несёт инструкцию подъёма, порог/логика тут не тронуты.
if [ -f "$RETIRED" ]; then
  echo 0 > "$F"   # серия слепых прогонов не должна пережить вывод из эксплуатации
  # Строку пишем ОДИН РАЗ на переход, а не каждые 5 мин: LOG усекается до 2000 строк и
  # 288 строк/сутки вымыли бы распределение threads=, на которое калибруется доля порога.
  case "$(tail -n 1 "$LOG" 2>/dev/null)" in
    (*retired=1*) : ;;
    (*) echo "$(date -u '+%F %H:%M') retired=1 маркер=$RETIRED — юнит выведен из эксплуатации, наблюдать нечего" >> "$LOG" ;;
  esac
  exit 0
fi

blind() {  # $1=причина $2=ключ дедупа. Серию считает файл-счётчик, тревога на 3-м подряд.
  C=$(( $(cat "$F" 2>/dev/null || echo 0) + 1 )); echo $C > "$F"
  [ "$C" -ge 3 ] && "$NOTIFY" threads-watch 0 \
    "🧵 сторож тредов НЕ ВИДИТ БОТА $C прогонов подряд: $1 — проверить" 21600 "$2"
  exit 1
}

# ОДИН ssh на прогон (эффект наблюдателя на боевой машине): числитель, ЖИВОЙ знаменатель и
# состав тредов забираются вместе. 28.08: прежний знаменатель был ВШИТОЙ СТРОКОЙ «/1024» —
# живой TasksMax оказался 2048 (рантаймный drop-in в /run), и порог 600, калиброванный как
# ~60% от 1024, звонил на 32% реального лимита. Самоотчёт шаблона режимом не является:
# лимит ЧИТАЕТСЯ, порог ВЫЧИСЛЯЕТСЯ долей (память quota-is-an-integral, 5-я форма).
# СОСТАВ ПИКА — тоже замером: py-spy на Шарлотте НЕТ, а к моменту побудки агента пик уже
# сходит (14:50 648 -> 15:00 174), т.е. предписанная прошлой тревогой диагностика была бы
# нулевым тестом. Гистограмма имён снимается В МОМЕНТ пересечения и едет В ТЕКСТ тревоги.
FRAC=${TW_FRAC:-0.6}
R=$(ssh -o ConnectTimeout=8 -o BatchMode=yes "$HOST" '
  BPID=$(systemctl show -p MainPID --value liquidator-bot)
  echo "N=$(ls /proc/$BPID/task 2>/dev/null | wc -l)"
  echo "MAX=$(systemctl show -p TasksMax --value liquidator-bot 2>/dev/null)"
  echo "PMAX=$(grep -h "^TasksMax=" /etc/systemd/system/liquidator-bot.service \
        /etc/systemd/system.control/liquidator-bot.service.d/*.conf 2>/dev/null \
        | tail -1 | cut -d= -f2)"
  echo "TOP=$(cat /proc/$BPID/task/*/comm 2>/dev/null | sed "s/[0-9]*$//" \
        | sort | uniq -c | sort -rn | head -4 | awk "{printf \"%s×%s \", \$2, \$1}")"
' 2>/dev/null)
N=$(printf '%s\n' "$R" | sed -n 's/^N=//p')
MAX=$(printf '%s\n' "$R" | sed -n 's/^MAX=//p')
PMAX=$(printf '%s\n' "$R" | sed -n 's/^PMAX=//p')
TOP=$(printf '%s\n' "$R" | sed -n 's/^TOP=//p')
case "$N" in (''|*[!0-9]*) blind "ssh/PID не дали числа" threads-blind ;; esac
# У ЖИВОГО процесса тредов всегда >=1. Ноль = MainPID=0: служба не бежит (или юнита нет).
# Три прогона подряд, а не первый: MainPID кратковременно 0 в момент рестарта systemd.
if [ "$N" -lt 1 ]; then
  blind "MainPID=0, служба liquidator-bot не бежит (треды не у кого считать)" threads-botdown
fi
# ЗНАМЕНАТЕЛЬ ТОЖЕ СУБЪЕКТ НАБЛЮДЕНИЯ: нечитаемый лимит = НЕ НАБЛЮДАЕМ, а не «возьмём 1024».
# Ровно ложный знаменатель и родил тревогу 28.08 — незнание обязано закрывать гард.
case "$MAX" in
  (infinity) echo 0 > "$F"; echo "$(date -u +%H:%M) threads=$N max=infinity" >> "$LOG"; exit 0 ;;
  (''|*[!0-9]*) blind "TasksMax не число ('$MAX') — знаменатель не наблюдаем" threads-nomax ;;
esac
echo 0 > "$F"
# Формат строки не переломан (`threads=N` первым полем): по нему считается распределение,
# на которое калибруется доля. Новые поля ДОПИСАНЫ, а не переставлены.
echo "$(date -u +%H:%M) threads=$N max=$MAX" >> "$LOG"
tail -n 2000 "$LOG" > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"
THR=$(awk -v m="$MAX" -v f="$FRAC" 'BEGIN{printf "%d", m*f}')
if [ "$N" -ge "$THR" ]; then
  # Тревога несёт числа, по которым судила (и свои, и эталонные), плюс чей пик — иначе
  # разбор начинается с перемера, а пика к тому времени уже нет.
  PN=${PMAX:-?}
  W=""
  [ "$PN" != "?" ] && [ "$PN" != "$MAX" ] && \
    W=" ⚠ персистентный лимит $PN ≠ живого $MAX (живой из /run — испарится на ребуте, порог пересчитается сам)"
  "$NOTIFY" threads-watch 0 \
    "🧵 ТРЕДЫ БОТА $N/$MAX (порог ${FRAC}×$MAX=$THR) — давление к шторму спавна. Состав СЕЙЧАС: ${TOP:-?}.$W Разбор агенту: душить ли поток, пора ли коллектор на путь окна (ревью-п.9)" 3600 threads-pressure
fi
exit 0
