# Выполняется НА БОЕВОЙ через `ssh host bash -s`. Печатает одной строкой 8 полей:
#   P A D ARMED Z NB NR NEAR
# P     — проб за 30 мин (probe #|volley leg=)
# A     — армов окна (shadow arm)
# D     — отказов по полу досягаемости (перехват детонатора ОТКЛОНЁН)
# ARMED — армленных досок
# Z     — армов, нашедших НОЛЬ кандидатов (targets=0) — «рынок пуст», не «прибор мёртв»
# NB    — арм-скипов с причиной «проба не собралась»  (ПОДПИСЬ ПОЛОМКИ 08:14-13:29: 6.4/мин)
# NR    — арм-скипов с причиной «вне досягаемости»    (подпись здорового отказа)
# NEAR  — ближайшая дистанция одним токеном, или «-»
# ВАЖНО: ни одно из этих полей НЕ ГЛУШИТ тревогу. Три попытки построить на них дискриминатор
# (27.08) были опровергнуты прогоном по эталону поломки: 'арм НЕ ВЗВЁЛСЯ' там 2003, '+вне
# досягаемости' 37, 'targets=0' 152 — каждое правило заглушило бы настоящую аварию. Поля идут
# В ТЕКСТ тревоги, чтобы читающий судил за один взгляд, а не за пять заходов по ssh.
L=$(journalctl -u liquidator-bot --since "-30min" --no-pager -o cat 2>/dev/null)
P=$(printf '%s' "$L" | grep -cE 'probe #|volley leg=')
A=$(printf '%s' "$L" | grep -c 'shadow arm')
D=$(printf '%s' "$L" | grep -c 'перехват детонатора ОТКЛОНЁН')
ARMED=$(printf '%s' "$L" | grep -c 'доска armed')
Z=$(printf '%s' "$L" | grep -c 'shadow arm.*targets=0 ')
NB=$(printf '%s' "$L" | grep -c 'арм НЕ ВЗВЁЛСЯ.*проба не собралась')
NR=$(printf '%s' "$L" | grep -c 'арм НЕ ВЗВЁЛСЯ.*вне досягаемости')
NEAR=$(printf '%s' "$L" | grep -oE 'dist [0-9.]+%' | awk '{print $2}' | sort -n | head -1)
echo "$P $A $D $ARMED $Z $NB $NR ${NEAR:--}"
