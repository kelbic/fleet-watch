#!/bin/bash
# ХОСТОВОЙ сетевой детектор флота ликвидаторов.
#
# ЗАЧЕМ. 24.07 все ЧЕТЫРЕ бота (World 480, Katana 747474, HyperEVM 999, Base 8453 —
# разные чейны, разные провайдеры) замерли в ОДНИ И ТЕ ЖЕ секунды: 13:03:21 и ~13:11:05,
# провалы 406с/406с/129с/404с. Это отказ egress ХОСТА, а не деградация какого-то чейна.
# Ни один прибор этого не увидел: cron-watchdog смотрит, что процесс жив (зависший жив и
# держит flock), deadman — что лог тикает (у каждого бота свой, и четыре одновременных 💀
# читались бы как четыре независимые поломки, а не как ОДНА общая причина).
#
# ЧТО ДЕЛАЕТ. Пробит НЕСКОЛЬКО независимых точек боевого пути + КОНТРОЛЬНЫЙ не-RPC хост.
# Алертит ТОЛЬКО когда лежит ВСЁ И повтор это подтвердил (иначе это деградация одного
# провайдера или одиночный таймаут — шум). Число точек — не деталь, а ЕДИНСТВЕННЫЙ
# источник специфичности: при одной точке «легло всё» значит «моргнула одна точка»
# (см. 10.09). Выводя чейн/бота, НЕ оставляй список короче двух точек.
# Контроль разделяет два диагноза: RPC=0 но контроль жив -> легли провайдеры/фильтрация;
# всё по нулям -> хост потерял egress. Плюс отдельная проба DNS (резолв не подчиняется
# сокетным таймаутам Python — классический источник «висит дольше таймаута»).
#
# ТИХИЙ РЕЖИМ. Алерт не чаще часа (штамп), и ровно ОДИН на инцидент + один на
# восстановление — у них РАЗНЫЕ ключи dedup, иначе ответный пинг съедается (баг до 10.09).
# Сторож меряет СВОИ пробы, а не проходы бота: вывод о слепоте бота делается по журналу
# бота, поэтому текст тревоги про боты ничего не утверждает. История каждой пробы пишется в netwatch.log — по ней можно будет
# скоррелировать будущий инцидент вместо гадания.
set -u
DIR=/home/claude-agent/.fleet-watch
LOG=$DIR/netwatch.log
STAMP=$DIR/.alerted            # взведён = инцидент уже отправлен (ждём восстановления)
THROTTLE=3600

# по одному эндпоинту на чейн, из тех же списков, что читают боты
PROBES=(
  # ВЫВЕДЕНО 01.09: боты World/Katana/HyperEVM сняты, чейны никто не читает.
  # 10.09: после вывода в списке осталась ОДНА точка — и «легли ВСЕ» выродилось в
  # «моргнула одна публичная точка» (тревога 16:36:11Z, разбор в архиве инбокса).
  # Специфичность этого сторожа ВСЕГДА держалась на И по нескольким НЕЗАВИСИМЫМ
  # провайдерам, поэтому список восстановлен по ширине — но теперь внутри Base:
  # это публичные точки того же пула, что читает боевой midnight (bot/executor.py:78),
  # т.е. критерий сторожа = критерий боевого пути, а не уже него. Ключевые URL сюда
  # не кладём: .fleet-watch — git-репозиторий.
  "base|https://mainnet.base.org"
  "base-pn|https://base-rpc.publicnode.com"
  "base-tn|https://gateway.tenderly.co/public/base"
  "base-bl|https://base-mainnet.public.blastapi.io"
)
CONTROL="https://1.1.1.1"      # не-RPC контроль: отделяет «легли провайдеры» от «лёг хост»
BODY='{"jsonrpc":"2.0","id":1,"method":"eth_chainId","params":[]}'

sweep() {  # один прогон по всем точкам; заполняет ok/total/detail
  ok=0; total=0; detail=""
  for p in "${PROBES[@]}"; do
    name=${p%%|*}; url=${p#*|}
    total=$((total+1))
    t0=$(date +%s%N)
    if curl -sS -m 8 -X POST -H 'Content-Type: application/json' \
         -H 'User-Agent: Mozilla/5.0' --data "$BODY" "$url" 2>/dev/null | grep -q '"result"'; then
      ms=$(( ($(date +%s%N)-t0)/1000000 )); ok=$((ok+1)); detail="$detail $name=${ms}ms"
    else
      ms=$(( ($(date +%s%N)-t0)/1000000 )); detail="$detail $name=FAIL(${ms}ms)"
    fi
  done
}

sweep
# ДЕБАУНС. Полный ноль — редчайшее событие (замер: rpc_ok=0 один раз на 14441 пробу),
# а одиночный таймаут курла — рядовое. Прежде чем звать агента, перепробить ЕЩЁ РАЗ:
# худший случай 2 прогона × 4 точки × 8с = 64с, помещается в каденцию крона (2 мин).
retried=""
if [ "$ok" -eq 0 ]; then
  sleep 5
  first="$detail"
  sweep
  retried=" [повтор; первый прогон:$first]"
fi

# контроль (не-RPC) и DNS — только для диагноза, в счёт ok не идут
ctl=FAIL; curl -sS -m 8 -o /dev/null "$CONTROL" 2>/dev/null && ctl=ok
dns=FAIL; getent hosts mainnet.base.org >/dev/null 2>&1 && dns=ok

ts=$(date -u '+%Y-%m-%dT%H:%M:%SZ')
echo "$ts rpc_ok=$ok/$total ctl=$ctl dns=$dns$detail$retried" >> "$LOG"
# лог не должен расти вечно (детектор тикает часто) — держим последние ~20k строк
if [ "$(wc -l < "$LOG" 2>/dev/null || echo 0)" -gt 20000 ]; then
  tail -n 10000 "$LOG" > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"
fi

send() {  # $1 = текст, $2 = ключ dedup. АДРЕСАТ — АГЕНТ (03.08): сетевой провал VPS
  # человек не чинит. При мёртвом egress запись в инбокс всё равно проходит (это локальный
  # файл), и агент разберёт её, когда сеть вернётся — тревога не теряется, а просто ждёт.
  # NETWATCH_TEST=1 — прогон контролей не должен стучаться в боевой инбокс.
  if [ "${NETWATCH_TEST:-0}" = "1" ]; then echo "[TEST send key=$2] $1"; return; fi
  /home/claude-agent/.fleet-watch/notify.sh netwatch 0 "$1" 900 "$2" > /dev/null
}

if [ "$ok" -eq 0 ]; then
  # ВСЁ легло. Диагноз по контролю: egress хоста или только RPC-провайдеры.
  if [ -f "$STAMP" ] && [ $(( $(date +%s) - $(stat -c %Y "$STAMP") )) -lt "$THROTTLE" ]; then
    exit 0
  fi
  if [ "$ctl" = "ok" ]; then
    diag="контроль (1.1.1.1) ЖИВ, DNS=$dns -> сеть хоста жива, легли/фильтруются RPC-провайдеры"
  else
    diag="контроль (1.1.1.1) ТОЖЕ мёртв, DNS=$dns -> ХОСТ потерял egress"
  fi
  send "🌐 [флот] НИ ОДНА RPC-точка не отвечает (0/$total), подтверждено повтором.$detail
$diag
Проверь ЖУРНАЛ БОТА (позитивный контроль), прежде чем делать вывод о его слепоте: сторож
меряет свои пробы, а не проходы бота. Проходы ограничены потолком и перезапустятся сами." netwatch
  touch "$STAMP"
elif [ -f "$STAMP" ]; then
  # восстановление после отправленного инцидента — ровно один ответный пинг
  # ключ ОТДЕЛЬНЫЙ: с общим ключом (ttl 900с) ответный пинг съедался dedup на любом
  # провале короче 15 минут — контракт «один на инцидент + один на восстановление» не
  # работал никогда (10.09: восстановление 16:38:01 съедено, инбокс остался с «всё легло»).
  send "✅ [флот] сеть восстановлена: RPC $ok/$total живы.$detail" netwatch-ok
  rm -f "$STAMP"
fi
